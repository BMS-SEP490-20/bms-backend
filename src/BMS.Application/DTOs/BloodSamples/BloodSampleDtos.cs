using System.ComponentModel.DataAnnotations;

namespace BMS.Application.DTOs.BloodSamples;

/// <summary>
/// Read model for the <c>TestOrder/BloodSample</c> endpoints (Print Barcodes #58, Validate Sample #73).
/// Backed by the shared <c>blood_samples</c> collection (<see cref="BMS.Core.Entities.Sample"/>).
/// </summary>
public class BloodSampleReadDto
{
    /// <summary>Sample document id.</summary>
    public string SampleId { get; set; } = null!;
    /// <summary>Appointment / test order the sample belongs to.</summary>
    public string AppointmentId { get; set; } = null!;
    /// <summary>Specimen type (Blood, Serum, Plasma, Urine).</summary>
    public string SampleType { get; set; } = null!;
    /// <summary>UTC collection time.</summary>
    public DateTime? CollectedAt { get; set; }
    /// <summary>Volume in millilitres.</summary>
    public decimal? Volume { get; set; }
    /// <summary>Lifecycle status (see <see cref="BMS.Core.Entities.SampleStatus"/>).</summary>
    public string? Status { get; set; }
    /// <summary>Physical storage location.</summary>
    public string? StorageLocation { get; set; }
    /// <summary>Free-text notes.</summary>
    public string? Notes { get; set; }
    /// <summary>Lab user currently responsible for the sample.</summary>
    public string? LabUserId { get; set; }
    /// <summary>Tube barcode printed on the label (falls back to the id for legacy samples without one).</summary>
    public string Barcode { get; set; } = null!;
    /// <summary>Collection time formatted for the label (yyyy-MM-dd HH:mm).</summary>
    public string? CollectionTimestamp => CollectedAt?.ToString("yyyy-MM-dd HH:mm");
}

/// <summary>Payload for registering a blood sample.</summary>
public class BloodSampleCreateDto
{
    /// <summary>Appointment / test order id.</summary>
    [Required]
    public string AppointmentId { get; set; } = null!;
    /// <summary>Specimen type.</summary>
    [Required]
    public string SampleType { get; set; } = null!;
    /// <summary>Optional client barcode; generated by the server when omitted.</summary>
    public string? Barcode { get; set; }
    /// <summary>UTC collection time; defaults to now.</summary>
    public DateTime? CollectedAt { get; set; }
    /// <summary>Volume in millilitres.</summary>
    [Range(0, 100)]
    public decimal? Volume { get; set; }
    /// <summary>Initial status name; defaults to Collected.</summary>
    public string? Status { get; set; }
    /// <summary>Physical storage location.</summary>
    public string? StorageLocation { get; set; }
    /// <summary>Free-text notes.</summary>
    public string? Notes { get; set; }
    /// <summary>Responsible lab user id.</summary>
    public string? LabUserId { get; set; }
}

/// <summary>Partial update payload; null fields are left unchanged.</summary>
public class BloodSampleUpdateDto
{
    /// <summary>Specimen type.</summary>
    public string? SampleType { get; set; }
    /// <summary>UTC collection time.</summary>
    public DateTime? CollectedAt { get; set; }
    /// <summary>Volume in millilitres.</summary>
    [Range(0, 100)]
    public decimal? Volume { get; set; }
    /// <summary>New status name (must be a valid SampleStatus).</summary>
    public string? Status { get; set; }
    /// <summary>Physical storage location.</summary>
    public string? StorageLocation { get; set; }
    /// <summary>Free-text notes.</summary>
    public string? Notes { get; set; }
    /// <summary>Responsible lab user id.</summary>
    public string? LabUserId { get; set; }
}

/// <summary>Validate Sample (#73) payload: <c>validated</c> accepts the specimen, <c>rejected</c> rejects it.</summary>
public class BloodSampleValidateDto
{
    /// <summary><c>validated</c> or <c>rejected</c>.</summary>
    [Required]
    public string Status { get; set; } = string.Empty;
    /// <summary>Verification notes / rejection reason.</summary>
    public string Notes { get; set; } = string.Empty;
    /// <summary>Lab user performing the validation.</summary>
    public string LabUserId { get; set; } = string.Empty;
}
